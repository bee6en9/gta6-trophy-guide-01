function compareTree(source, target) {
  const names = readdirSync(source).sort();
  assert.deepEqual(readdirSync(target).sort(), names);
  for (const name of names) {
    const from = join(source, name);
    const to = join(target, name);
    if (statSync(from).isDirectory()) compareTree(from, to);
    else assert.deepEqual(readFileSync(from), readFileSync(to), 'Copied bytes: ' + from);
  }
}
for (const output of ['out', 'out2']) {
  compareTree('app', join(output, 'app'));
  compareTree('screenshots', join(output, 'screenshots'));
}
